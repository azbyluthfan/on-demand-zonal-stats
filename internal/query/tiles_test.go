func tileAt(lon, lat float64, z int) query.Tile {
	t := maptile.At(orb.Point{lon, lat}, maptile.Zoom(z))
	return query.Tile{Z: z, X: int(t.X), Y: int(t.Y)}
}

// decode unmarshals an MVT and projects it back to lon/lat.
func decode(t *testing.T, data []byte, tl query.Tile) map[string]mvt.Layer {
	t.Helper()
	ls, err := mvt.Unmarshal(data)
	if err != nil {
		t.Fatalf("decode MVT: %v", err)
	}
	ls.ProjectToWGS84(maptile.New(uint32(tl.X), uint32(tl.Y), maptile.Zoom(tl.Z)))
	out := map[string]mvt.Layer{}
	for _, l := range ls {
		out[l.Name] = *l
	}
	return out
}

func TestParseTileAndBounds(t *testing.T) {
	for _, bad := range [][4]string{{"12", "1", "1.png", ".mvt"}, {"x", "1", "1.mvt", ".mvt"}, {"3", "8", "0.mvt", ".mvt"},
		{"-1", "0", "0.mvt", ".mvt"}, {"23", "0", "0.mvt", ".mvt"}} {
		if _, err := query.ParseTile(bad[0], bad[1], bad[2], bad[3]); !errors.Is(err, query.ErrBadTile) {
			t.Errorf("ParseTile%v: err %v, want ErrBadTile", bad, err)
		}
	}
	tl, err := query.ParseTile("13", "6607", "4274.mvt", ".mvt")
	if err != nil || tl != (query.Tile{Z: 13, X: 6607, Y: 4274}) {
		t.Fatalf("ParseTile = %+v, %v", tl, err)
	}
	// Bounds agree with orb's independent maptile implementation.
	want := maptile.New(6607, 4274, 13).Bound()
	got := tl.Bound(0)
	for i, d := range []float64{got.Min[0] - want.Min[0], got.Min[1] - want.Min[1], got.Max[0] - want.Max[0], got.Max[1] - want.Max[1]} {
		if math.Abs(d) > 1e-9 {
			t.Errorf("bound component %d off by %g: %v vs %v", i, d, got, want)
		}
	}
}

// Vector tiles are generated by DuckDB (ST_AsMVT); decoding them must give
// back the release's features where they are, with the requested filters.
func TestVectorTilesFixture(t *testing.T) {
	e := openFixture(t)
	ctx := context.Background()

	// z8 covers every fixture village (a z9 tile edge falls at 110.39°).
	tl := tileAt(110.38, -7.83, 8)
	res, err := e.VectorTile(ctx, "villages", tl, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	ls := decode(t, res.Data, tl)
	got := map[string]bool{}
	for _, f := range ls["villages"].Features {
		got[f.Properties.MustString("village_id")] = true
		if _, ok := f.Geometry.(orb.Polygon); !ok {
			if _, ok := f.Geometry.(orb.MultiPolygon); !ok {
				t.Errorf("village %v geometry %T", f.Properties["village_id"], f.Geometry)
			}
		}
	}
	for _, v := range testfixtures.Villages(t) {
		// V005 (a ~55 m triangle) is smaller than one tile unit at z8
		// (~150 m) and is generalised away, like any sub-pixel feature.
		if got[v.ID] == (v.ID == "V005") {
			t.Errorf("village %s present=%v in z8 tile (got %v)", v.ID, got[v.ID], got)
		}
	}
	if res.Features != int64(len(ls["villages"].Features)) || res.DuckDB <= 0 {
		t.Errorf("result stats %+v", res)
	}
	z14 := tileAt(110.42, -7.8003, 14)
	res, err = e.VectorTile(ctx, "villages", z14, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	found := false
	for _, f := range decode(t, res.Data, z14)["villages"].Features {
		found = found || f.Properties.MustString("village_id") == "V005"
	}
	if !found {
		t.Error("V005 missing at z14")
	}

	// Below minzoom: empty.
	if res, err := e.VectorTile(ctx, "pois", tileAt(110.31, -7.81, 10), nil, true); err != nil || len(res.Data) != 0 {
		t.Errorf("below minzoom: %d bytes, %v", len(res.Data), err)
	}

	// POIs at z14 around V001: exactly the fixture POIs inside the tile
	// (plus buffer), at their positions, filtered by category.
	tl = tileAt(110.31, -7.81, 14)
	buf := tl.Bound(64.0 / 4096)
	for _, cats := range [][]string{nil, {"cafe"}} {
		res, err := e.VectorTile(ctx, "pois", tl, cats, true)
		if err != nil {
			t.Fatal(err)
		}
		want := 0
		for _, p := range fixturePOIs(t) {
			if buf.Contains(p.p) && (cats == nil || p.category == cats[0]) {
				want++
			}
		}
		feats := decode(t, res.Data, tl)["pois"].Features
		if len(feats) != want || want == 0 {
			t.Errorf("categories %v: %d POIs in tile, want %d", cats, len(feats), want)
		}
		for _, f := range feats {
			if cats != nil && f.Properties.MustString("category") != cats[0] {
				t.Errorf("category filter leaked %v", f.Properties["category"])
			}
		}
	}
	// Positions survive the round trip to within one tile unit.
	res, _ = e.VectorTile(ctx, "pois", tl, nil, true)
	unit := (tl.Bound(0).Max[0] - tl.Bound(0).Min[0]) / 4096
	for _, f := range decode(t, res.Data, tl)["pois"].Features {
		p := f.Geometry.(orb.Point)
		best := math.Inf(1)
		for _, fp := range fixturePOIs(t) {
			best = min(best, math.Hypot(fp.p[0]-p[0], fp.p[1]-p[1]))
		}
		if best > 2*unit {
			t.Errorf("decoded POI %v is %g° from any fixture POI (unit %g)", p, best, unit)
		}
	}

	// Buildings: two layers in one tile (cells + points), and h3 cells.
	tl = tileAt(110.38, -7.82, 14)
	res, err = e.VectorTile(ctx, "buildings", tl, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	bl := decode(t, res.Data, tl)
	if len(bl["building_cells"].Features)+len(bl["building_points"].Features) == 0 {
		t.Errorf("no buildings in tile over V004: %v", bl)
	}
	res, err = e.VectorTile(ctx, "h3", tl, nil, true)
	if err != nil {
		t.Fatal(err)
	}
	kinds := map[string]int{}
	for _, f := range decode(t, res.Data, tl)["h3"].Features {
		kinds[f.Properties.MustString("cell_type")]++
	}
	if kinds["interior"] == 0 || kinds["boundary"] == 0 {
		t.Errorf("h3 tile cell types %v", kinds)
	}

	// Cache: a second request is served from the tile cache, identical.
	a, _ := e.VectorTile(ctx, "h3", tl, nil, false)
	b, _ := e.VectorTile(ctx, "h3", tl, nil, false)
	if a.Cached || !b.Cached || !bytes.Equal(a.Data, b.Data) {
		t.Errorf("tile cache: first cached=%v second cached=%v equal=%v", a.Cached, b.Cached, bytes.Equal(a.Data, b.Data))
	}

	for _, c := range []struct {
		layer string
		cats  []string
	}{{"nope", nil}, {"pois", []string{"spaceport"}}} {
		if _, err := e.VectorTile(ctx, c.layer, tl, c.cats, true); !errors.Is(err, query.ErrBadTile) {
			t.Errorf("%s %v: err %v, want ErrBadTile", c.layer, c.cats, err)
		}
	}
}

// Raster tiles: land cover pixels take their class colours (bands of the
// fixture grid), and continuous breaks are increasing deciles.
func TestRasterTilesFixture(t *testing.T) {
	e, err := query.Open(context.Background(), query.Options{Base: testfixtures.ReleaseWithRasters(t), AllowInstall: true})
	if err != nil {
		t.Fatal(err)
	}
	defer e.Close()
	ctx := context.Background()
	tl := tileAt(110.33, -7.82, 12)
	res, err := e.RasterTile(ctx, "landcover", tl, true)
	if err != nil {
		t.Fatal(err)
	}
	img, err := png.Decode(bytes.NewReader(res.Data))
	if err != nil {
		t.Fatal(err)
	}
	b := tl.Bound(0)
	px := func(lon, lat float64) string { // pixel at lon/lat, as #rrggbb
		x := int((lon - b.Min[0]) / (b.Max[0] - b.Min[0]) * 256)
		f := maptile.Fraction(orb.Point{lon, lat}, maptile.Zoom(tl.Z))
		y := int((f[1] - float64(tl.Y)) * 256)
		r, g, bb, a := img.At(x, y).RGBA()
		if a == 0 {
			return "transparent"
		}
		return fmt.Sprintf("#%02x%02x%02x", r>>8, g>>8, bb>>8)
	}
	for _, c := range []struct {
		lon, lat float64
		want     string
	}{{110.305, -7.82, "#006400"}, {110.345, -7.82, "#f096ff"}} { // class 10 west of 110.32, 40 east
		if got := px(c.lon, c.lat); got != c.want {
			t.Errorf("pixel at %v,%v = %s, want %s", c.lon, c.lat, got, c.want)
		}
	}
	// Outside the raster: transparent.
	far := tileAt(111.5, -7.0, 12)
	if res, err := e.RasterTile(ctx, "landcover", far, true); err != nil {
		t.Fatal(err)
	} else if img, _ := png.Decode(bytes.NewReader(res.Data)); img != nil {
		if _, _, _, a := img.At(128, 128).RGBA(); a != 0 {
			t.Error("tile outside the raster is not transparent")
		}
	}

	lg, err := e.Legend(ctx, "population_2020")
	if err != nil {
		t.Fatal(err)
	}
	if len(lg.Breaks) < 5 || len(lg.Colors) != len(lg.Breaks)+1 {
		t.Fatalf("legend %+v", lg)
	}
	for i := 1; i < len(lg.Breaks); i++ {
		if lg.Breaks[i] <= lg.Breaks[i-1] {
			t.Errorf("breaks not increasing: %v", lg.Breaks)
		}
	}
	// Fixture values are 1..12.75 (gen_fixtures.py).
	if lg.Breaks[0] < 1 || lg.Breaks[len(lg.Breaks)-1] > 12.75 {
		t.Errorf("breaks %v outside the fixture's value range", lg.Breaks)
	}
	if lc, err := e.Legend(ctx, "landcover"); err != nil || lc.Kind != "categorical" || len(lc.Classes) != 4 {
		t.Errorf("landcover legend %+v %v", lc, err)
	}
}

// Tiles are byte-identical across cold runs (ordered ST_AsMVT aggregate).
func TestVectorTilesDeterministic(t *testing.T) {
	e := openFixture(t)
	for _, c := range []struct {
		layer string
		tl    query.Tile
	}{{"pois", tileAt(110.31, -7.81, 14)}, {"buildings", tileAt(110.38, -7.82, 14)}, {"h3", tileAt(110.38, -7.82, 14)}, {"villages", tileAt(110.38, -7.83, 8)}} {
		var first []byte
		for i := 0; i < 5; i++ {
			res, err := e.VectorTile(context.Background(), c.layer, c.tl, nil, true)
			if err != nil {
				t.Fatal(err)
			}
			if i == 0 {
				first = res.Data
			} else if !bytes.Equal(first, res.Data) {
				t.Fatalf("%s tile differs between cold runs", c.layer)
			}
		}
	}
}
